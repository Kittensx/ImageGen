export function samplerDescriptor(name) {
  return state.samplers.find((item) => item.name === name || item.plugin_id === name) || null;
}

export function schedulerDescriptor(name) {
  return state.schedulers.find((item) => item.name === name || item.plugin_id === name) || null;
}

export function setCatalogs(payload) {
  state.models = payload.models?.models || payload.models || state.models;
  state.vaes = payload.models?.vaes || payload.vaes || state.vaes;
  state.samplers = payload.plugins?.samplers || state.samplers;
  state.schedulers = payload.plugins?.schedulers || state.schedulers;
  state.promptParsers = payload.prompt_parsers || payload.promptParsers || state.promptParsers;
  state.promptShortcutProfiles = payload.prompt_shortcut_profiles || payload.promptShortcutProfiles || state.promptShortcutProfiles;
  state.promptParserPresets = payload.prompt_parser_presets || payload.promptParserPresets || state.promptParserPresets;
}
